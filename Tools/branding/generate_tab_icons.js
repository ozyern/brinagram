// Generates the dock tab vector icons (original geometry) into res/drawable.
// Usage: node Tools/branding/generate_tab_icons.js TMessagesProj/src/main/res
const fs = require('fs'), path = require('path');
const f = n => +n.toFixed(3);
const pt = (r, deg, cx = 12, cy = 12) => { const a = deg * Math.PI / 180; return [f(cx + r * Math.cos(a)), f(cy + r * Math.sin(a))]; };
const circle = (cx, cy, r) => `M${f(cx - r)},${cy} a${r},${r} 0 1,0 ${f(2 * r)},0 a${r},${r} 0 1,0 ${f(-2 * r)},0 Z`;

// Gear: 10 rounded teeth (outer ring), a transparent gap, then a hub disc with a Y cut out.
function gear() {
  const teeth = 10, rOut = 11.2, rRoot = 9.1, step = 360 / teeth, topHalf = step * 0.22, baseHalf = step * 0.33;
  let d = '';
  for (let i = 0; i < teeth; i++) {
    const c = i * step - 90;
    const pts = [pt(rRoot, c - baseHalf), pt(rOut, c - topHalf), pt(rOut, c + topHalf), pt(rRoot, c + baseHalf), pt(rRoot, c + step - baseHalf)];
    pts.forEach((p, j) => { d += (i === 0 && j === 0 ? 'M' : 'L') + p.join(','); });
  }
  d += 'Z ' + circle(12, 12, 6.7);           // gear ring hole
  // Hub: three pie wedges separated by spoke-shaped gaps (reads as a "Y" hub).
  const r = 5.3, h = 0.72, arms = [90, 210, 330];
  const t = Math.sqrt(r * r - h * h), inner = h / Math.sin(Math.PI / 3);
  let hub = '';
  for (let i = 0; i < 3; i++) {
    const a = arms[i] * Math.PI / 180, b = (arms[i] + 120) * Math.PI / 180;
    const pa = [f(12 + t * Math.cos(a) + h * Math.cos(a + Math.PI / 2)), f(12 + t * Math.sin(a) + h * Math.sin(a + Math.PI / 2))];
    const pb = [f(12 + t * Math.cos(b) + h * Math.cos(b - Math.PI / 2)), f(12 + t * Math.sin(b) + h * Math.sin(b - Math.PI / 2))];
    const mid = pt(inner, arms[i] + 60);
    hub += 'M' + mid.join(',') + 'L' + pa.join(',') + 'A' + r + ',' + r + ' 0 0,1 ' + pb.join(',') + 'Z ';
  }
  return [d, hub.trim()];
}

// Person in a filled circle: head and shoulders cut out, shoulders cropped by the circle.
function person() {
  const head = circle(12, 9.2, 3.9);
  const yb = 19.0, dx = Math.sqrt(121 - Math.pow(yb - 12, 2));
  const L = [f(12 - dx), yb], Rr = [f(12 + dx), yb];
  // Circle with the bottom replaced by the shoulder curve; the head is an even-odd hole.
  const silhouette = `M${L.join(',')} A11,11 0 1,1 ${Rr.join(',')} C${f(12 + dx - 1.6)},15.6 ${f(14.8)},14.6 12,14.6 C${f(9.2)},14.6 ${f(12 - dx + 1.6)},15.6 ${L.join(',')} Z`;
  return silhouette + ' ' + head;
}

const vector = (paths) => `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by Tools/branding/generate_tab_icons.js -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp" android:height="24dp"
    android:viewportWidth="24" android:viewportHeight="24">
${paths.map(p => `    <path android:fillColor="#FFFFFFFF" android:fillType="evenOdd" android:pathData="${p}" />`).join('\n')}
</vector>
`;
const res = process.argv[2];
fs.writeFileSync(path.join(res, 'drawable', 'brina_tab_settings.xml'), vector(gear()));
fs.writeFileSync(path.join(res, 'drawable', 'brina_tab_contacts.xml'), vector([person()]));
console.log('ok');
